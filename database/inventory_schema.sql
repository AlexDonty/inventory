-- =========================================================
-- INVENTORY DATABASE SCHEMA
-- =========================================================

-- 1. CATÁLOGO DE CATEGORÍAS
CREATE TABLE CAT_CATEGORY (
    ID NUMBER(19,0) GENERATED BY DEFAULT AS IDENTITY,
    CATEGORY VARCHAR2(255) NOT NULL,
    CATEGORY_CODE VARCHAR2(50) NOT NULL,
    CONSTRAINT PK_CAT_CATEGORY PRIMARY KEY (ID),
    CONSTRAINT UK_CATEGORY_CODE UNIQUE (CATEGORY_CODE)
);

-- 2. CATÁLOGO DE ESTADOS
CREATE TABLE CAT_STATUS (
    ID NUMBER(19,0) GENERATED BY DEFAULT AS IDENTITY,
    STATUS VARCHAR2(255) NOT NULL,
    CONSTRAINT PK_CAT_STATUS PRIMARY KEY (ID),
    CONSTRAINT UK_CAT_STATUS UNIQUE (STATUS)
);

-- 3. INVENTARIO DE ACTIVOS TECNOLÓGICOS
CREATE TABLE TAB_TECHNOLOGICAL_ASSETS (
    ID VARCHAR2(36 CHAR) NOT NULL,
    ACQUISITION_COST NUMBER(15,2) NOT NULL,
    ENTRY_DATE TIMESTAMP(6) DEFAULT SYSTIMESTAMP NOT NULL,
    INVENTORY_FOLIO VARCHAR2(50) NOT NULL,
    MODEL VARCHAR2(255 CHAR) NOT NULL,
    SERIAL_NUMBER VARCHAR2(100) NOT NULL,
    CATEGORY_ID NUMBER(19,0) NOT NULL,
    STATUS_ID NUMBER(19,0) NOT NULL,
    CONSTRAINT PK_TECH_ASSETS PRIMARY KEY (ID),
    CONSTRAINT UK_TECH_FOLIO UNIQUE (INVENTORY_FOLIO),
    CONSTRAINT UK_TECH_SERIAL UNIQUE (SERIAL_NUMBER),

    CONSTRAINT FK_TECH_CATEGORY
        FOREIGN KEY (CATEGORY_ID)
        REFERENCES CAT_CATEGORY(ID),

    CONSTRAINT FK_TECH_STATUS
        FOREIGN KEY (STATUS_ID)
        REFERENCES CAT_STATUS(ID)
);

-- 4. SECUENCIA
CREATE SEQUENCE SEQ_INVENTORY_FOLIO
START WITH 1
INCREMENT BY 1
NOCYCLE
CACHE 20;

-- 5. FUNCIÓN GENERADORA DE FOLIO
CREATE OR REPLACE FUNCTION FN_GENERATE_INVENTORY_FOLIO(
    P_PREFIX IN VARCHAR2
)
RETURN VARCHAR2
IS
    V_NUMBER NUMBER;
BEGIN
    V_NUMBER := SEQ_INVENTORY_FOLIO.NEXTVAL;

    RETURN P_PREFIX || '-' ||
           TO_CHAR(SYSDATE, 'YYYY') || '-' ||
           LPAD(
               TO_CHAR(V_NUMBER),
               GREATEST(6, LENGTH(TO_CHAR(V_NUMBER))),
               '0'
           );
END;
/

-- 6. TRIGGER DE FOLIO
CREATE OR REPLACE TRIGGER TRG_TECH_ASSET_FOLIO
BEFORE INSERT ON TAB_TECHNOLOGICAL_ASSETS
FOR EACH ROW
DECLARE
    V_PREFIX VARCHAR2(50);
BEGIN
    SELECT CATEGORY_CODE
    INTO V_PREFIX
    FROM CAT_CATEGORY
    WHERE ID = :NEW.CATEGORY_ID;

    IF :NEW.INVENTORY_FOLIO IS NULL THEN
        :NEW.INVENTORY_FOLIO :=
            FN_GENERATE_INVENTORY_FOLIO(V_PREFIX);
    END IF;
END;
/

